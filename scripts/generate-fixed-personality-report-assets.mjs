import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const root = process.cwd();

const sourceRoot = path.join(
  root,
  "docs",
  "assessment-professionalization",
  "final-report",
);

const outputPath = path.join(
  root,
  "src",
  "data",
  "report",
  "fixed-assets",
  "generated-report-markdown.ts",
);

const personalityTypes = [
  "ENFJ",
  "ENFP",
  "ENTJ",
  "ENTP",
  "ESFJ",
  "ESFP",
  "ESTJ",
  "ESTP",
  "INFJ",
  "INFP",
  "INTJ",
  "INTP",
  "ISFJ",
  "ISFP",
  "ISTJ",
  "ISTP",
];

const profiles = ["A", "B", "C", "D"];

const assets = {};
let sourceCount = 0;

function sha256(content) {
  return crypto
    .createHash("sha256")
    .update(content, "utf8")
    .digest("hex");
}

for (const personalityType of personalityTypes) {
  const typeDir = path.join(
    sourceRoot,
    personalityType.toLowerCase(),
  );

  if (!fs.existsSync(typeDir)) {
    throw new Error(
      `Missing report directory: ${typeDir}`,
    );
  }

  assets[personalityType] = {};

  for (const profile of profiles) {
    const fileName =
      `InnerGeo_${personalityType}_Profile_${profile}` +
      `_FINAL_Customer_v1.md`;

    const filePath = path.join(
      typeDir,
      fileName,
    );

    if (!fs.existsSync(filePath)) {
      throw new Error(
        `Missing canonical report: ${filePath}`,
      );
    }

    const markdown = fs.readFileSync(
      filePath,
      "utf8",
    );

    if (!markdown.trim()) {
      throw new Error(
        `Empty canonical report: ${filePath}`,
      );
    }

    const relativeSourcePath = path
      .relative(root, filePath)
      .split(path.sep)
      .join("/");

    assets[personalityType][profile] = {
      sourcePath: relativeSourcePath,
      sha256: sha256(markdown),
      markdown,
    };

    sourceCount += 1;
  }

  const matchingFiles = fs
    .readdirSync(typeDir)
    .filter((name) =>
      name.startsWith(
        `InnerGeo_${personalityType}_Profile_`,
      ) &&
      name.includes(
        "_FINAL_Customer_v1",
      ) &&
      name.endsWith(".md"),
    );

  if (matchingFiles.length !== 4) {
    throw new Error(
      `${personalityType}: expected exactly 4 FINAL Customer files, found ${matchingFiles.length}`,
    );
  }
}

if (sourceCount !== 64) {
  throw new Error(
    `Expected 64 canonical reports, found ${sourceCount}`,
  );
}

const serializedAssets =
  JSON.stringify(assets, null, 2);

const generated = `/*
 * AUTO-GENERATED FILE.
 *
 * Source:
 * docs/assessment-professionalization/final-report/<type>/
 *
 * Do not edit this file manually.
 * Regenerate with:
 * node scripts/generate-fixed-personality-report-assets.mjs
 */

import type {
  PersonalityTypeCode,
} from "../../personality/types";
import type {
  PersonalityReportProfile,
} from "../generator/profile-resolver";

export interface FixedPersonalityReportMarkdownAsset {
  readonly sourcePath: string;
  readonly sha256: string;
  readonly markdown: string;
}

export const FIXED_PERSONALITY_REPORT_MARKDOWN =
${serializedAssets} as const satisfies Readonly<
  Record<
    PersonalityTypeCode,
    Readonly<
      Record<
        PersonalityReportProfile,
        FixedPersonalityReportMarkdownAsset
      >
    >
  >
>;

export const FIXED_PERSONALITY_REPORT_COUNT = 64 as const;
`;

fs.writeFileSync(
  outputPath,
  generated,
  "utf8",
);

console.log(
  "===== FIXED REPORT ASSET GENERATOR =====",
);
console.log(
  `SOURCE_COUNT=${sourceCount}`,
);
console.log(
  `OUTPUT=${path.relative(root, outputPath)}`,
);
console.log(
  `OUTPUT_BYTES=${fs.statSync(outputPath).size}`,
);
console.log(
  "GENERATION=PASS",
);
